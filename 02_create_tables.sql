

USE LibraryDB;
GO

CREATE TABLE Members (
    MemberID INT IDENTITY(1,1) PRIMARY KEY,
    FullName NVARCHAR(100) NOT NULL,
    Email NVARCHAR(150) NOT NULL UNIQUE,
    JoinDate DATE NOT NULL DEFAULT GETDATE()
);
GO

CREATE TABLE Books (
    BookID INT IDENTITY(1,1) PRIMARY KEY,
    Title NVARCHAR(200) NOT NULL,
    Author NVARCHAR(100) NOT NULL,
    PublishedYear INT NULL,
    CopiesAvailable INT NOT NULL DEFAULT 1,
    CONSTRAINT CK_Books_Copies CHECK (CopiesAvailable >= 0),
    CONSTRAINT CK_Books_Year CHECK (PublishedYear BETWEEN 1000 AND 2100)
);
GO

CREATE TABLE Loans (
    LoanID INT IDENTITY(1,1) PRIMARY KEY,
    MemberID INT NOT NULL,
    BookID INT NOT NULL,
    LoanDate DATE NOT NULL DEFAULT GETDATE(),
    DueDate DATE NOT NULL,
    ReturnDate DATE NULL,
    CONSTRAINT FK_Loans_Members FOREIGN KEY (MemberID) REFERENCES Members(MemberID),
    CONSTRAINT FK_Loans_Books FOREIGN KEY (BookID) REFERENCES Books(BookID),
    CONSTRAINT CK_Loans_Dates CHECK (DueDate >= LoanDate)
);
GO